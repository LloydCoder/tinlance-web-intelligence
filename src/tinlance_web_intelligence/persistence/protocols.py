"""Structural contracts shared by single-node and PostgreSQL persistence adapters."""
from __future__ import annotations

from typing import Any, Protocol

from tinlance_web_intelligence.commercial.usage_ledger import UsageEvent
from tinlance_web_intelligence.integrations.world_intelligence.outbox import OutboxEvent
from tinlance_web_intelligence.jobs.model import Job


class JobRepository(Protocol):
    def create(self, *, tenant_id: str, subject_id: str, kind: str,
               payload: dict[str, Any], idempotency_key: str,
               traceparent: str | None = None) -> Job: ...
    def get(self, job_id: str, *, tenant_id: str,
            subject_id: str | None = None) -> Job | None: ...
    def claim_next(self, worker_id: str, *, lease_seconds: int = 60,
                   allowed_kinds: tuple[str, ...] | None = None) -> Job | None: ...
    def complete(self, job_id: str, worker_id: str, result: dict[str, Any]) -> Job: ...
    def fail(self, job_id: str, worker_id: str, *, error_code: str,
             retryable: bool) -> Job: ...
    def cancel(self, job_id: str, *, tenant_id: str, subject_id: str) -> Job | None: ...
    def metrics_snapshot(self) -> dict[str, float]: ...
    def ping(self) -> bool: ...
    def close(self) -> None: ...


class SourceEvidenceOutbox(Protocol):
    def enqueue(self, *, tenant_ref: str, subject_ref: str, idempotency_key: str,
                payload: dict[str, Any], request_id: str,
                traceparent: str | None) -> tuple[OutboxEvent, bool]: ...
    def claim_next(self, worker_id: str, *, lease_seconds: int = 60) -> OutboxEvent | None: ...
    def complete(self, event_id: str, lease_token: str,
                 remote_evidence_id: str) -> OutboxEvent: ...
    def fail(self, event_id: str, lease_token: str, *, error_code: str,
             retryable: bool, max_attempts: int = 5) -> OutboxEvent: ...
    def get(self, event_id: str, tenant_ref: str,
            subject_ref: str) -> OutboxEvent | None: ...
    def metrics_snapshot(self) -> dict[str, float]: ...
    def ping(self) -> bool: ...
    def close(self) -> None: ...



class UsageLedger(Protocol):
    def reserve(
        self, *, tenant_id: str, subject_id: str, feature: str, dimension: str,
        period_start: str, quantity: int, limit: int, idempotency_key: str,
    ) -> Any: ...
    def commit(self, *, tenant_id: str, subject_id: str, reservation_id: str) -> UsageEvent: ...
    def release(self, *, tenant_id: str, subject_id: str, reservation_id: str) -> bool: ...
    def usage_total(
        self, *, tenant_id: str, subject_id: str | None, dimension: str, period_start: str
    ) -> int: ...
    def list_events(
        self, *, tenant_id: str, subject_id: str | None, limit: int = 100,
        dimension: str | None = None, period_start: str | None = None,
        after: tuple[str, str] | None = None,
    ) -> list[UsageEvent]: ...
    def close(self) -> None: ...
